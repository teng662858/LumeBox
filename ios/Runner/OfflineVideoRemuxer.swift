import Foundation
import CommonCrypto
import AetherLibavformat
import AetherLibavcodec
import AetherLibavutil

/// Local HLS -> MP4 stream copy. No decoders, encoders, or origin connections are used.
final class OfflineVideoRemuxer: @unchecked Sendable {
  private let lock = NSLock()
  private var cancelled = false
  func cancel() { lock.lock(); cancelled = true; lock.unlock() }
  private func check() throws {
    lock.lock(); let stopped = cancelled; lock.unlock()
    if stopped { throw CancellationError() }
  }
  private func failure(_ text: String, _ code: Int32 = 0) -> NSError {
    NSError(domain: "LumeBox.Remux", code: Int(code), userInfo: [NSLocalizedDescriptionKey: text])
  }

  func merge(directory: URL) throws {
    let root = directory.resolvingSymlinksInPath().standardizedFileURL
    let workspace = root.appendingPathComponent(".remux-work", isDirectory: true)
    let output = root.appendingPathComponent("merged.mp4.part")
    let fm = FileManager.default
    if fm.fileExists(atPath: workspace.path) { try fm.removeItem(at: workspace) }
    try fm.createDirectory(at: workspace, withIntermediateDirectories: true)
    defer { try? fm.removeItem(at: workspace) }
    let input = try prepare(root.appendingPathComponent("index.m3u8"), root: root,
                            workspace: workspace, depth: 0)
    do {
      try copyPackets(input: input, output: output)
      try check()
      try validate(output)
    } catch {
      try? fm.removeItem(at: output)
      throw error
    }
  }

  private func local(_ reference: String, relativeTo playlist: URL, root: URL) throws -> URL {
    // Playlists are generated by LumeBox. Refuse a stale network or escaping reference.
    guard URL(string: reference)?.scheme == nil, !reference.hasPrefix("/") else {
      throw failure("离线清单包含非本地地址")
    }
    let url = playlist.deletingLastPathComponent().appendingPathComponent(reference)
      .resolvingSymlinksInPath().standardizedFileURL
    guard url.path.hasPrefix(root.path + "/"), FileManager.default.fileExists(atPath: url.path) else {
      throw failure("离线文件缺失或路径无效")
    }
    return url
  }

  private func attribute(_ name: String, in line: String) -> String? {
    let pattern = "(?:^|[:,])" + name + "=(?:\"([^\"]*)\"|([^,]*))"
    guard let regex = try? NSRegularExpression(pattern: pattern),
          let match = regex.firstMatch(in: line, range: NSRange(line.startIndex..., in: line)) else { return nil }
    for i in [1, 2] {
      if let range = Range(match.range(at: i), in: line) { return String(line[range]) }
    }
    return nil
  }

  private func iv(_ text: String?, sequence: UInt64) throws -> Data {
    if let text = text {
      var hex = text.lowercased()
      if hex.hasPrefix("0x") { hex.removeFirst(2) }
      guard !hex.isEmpty, hex.count <= 32, hex.allSatisfy({ $0.isHexDigit }) else {
        throw failure("HLS 加密 IV 无效")
      }
      hex = String(repeating: "0", count: 32 - hex.count) + hex
      return Data(stride(from: 0, to: 32, by: 2).map { offset in
        let start = hex.index(hex.startIndex, offsetBy: offset)
        return UInt8(hex[start..<hex.index(start, offsetBy: 2)], radix: 16)!
      })
    }
    var result = Data(repeating: 0, count: 16)
    for i in 0..<8 { result[15 - i] = UInt8(truncatingIfNeeded: sequence >> (8 * i)) }
    return result
  }

  /// Rewrite a bounded graph; AES-128 is decrypted into disposable local files because the
  /// bundled FFmpeg intentionally has no network/crypto protocol. Original downloads stay intact.
  private func prepare(_ playlist: URL, root: URL, workspace: URL, depth: Int) throws -> URL {
    try check()
    guard depth <= 3 else { throw failure("播放清单嵌套过深") }
    let data = try Data(contentsOf: playlist)
    guard data.count <= 4 * 1024 * 1024, let body = String(data: data, encoding: .utf8),
          body.hasPrefix("#EXTM3U") else { throw failure("离线清单无效") }
    let lines = body.components(separatedBy: .newlines)
    let master = lines.contains { $0.hasPrefix("#EXT-X-STREAM-INF:") }
    guard master || lines.contains("#EXT-X-ENDLIST") else { throw failure("不能合并直播清单") }
    var key: Data?, explicitIV: String?, sequence: UInt64 = 0
    var rewritten: [String] = []
    for raw in lines {
      try check()
      let line = raw.trimmingCharacters(in: .whitespacesAndNewlines)
      if line.hasPrefix("#EXT-X-MEDIA-SEQUENCE:") {
        guard let value = UInt64(line.dropFirst("#EXT-X-MEDIA-SEQUENCE:".count)) else {
          throw failure("分片序号无效")
        }
        sequence = value
      }
      if line.hasPrefix("#EXT-X-KEY:") {
        let method = attribute("METHOD", in: line)
        if method == "NONE" { key = nil; explicitIV = nil }
        else {
          guard method == "AES-128", let ref = attribute("URI", in: line),
                attribute("KEYFORMAT", in: line) == nil || attribute("KEYFORMAT", in: line) == "identity" else {
            throw failure("不支持该视频加密格式")
          }
          key = try Data(contentsOf: local(ref, relativeTo: playlist, root: root))
          guard key?.count == 16 else { throw failure("AES 密钥无效") }
          explicitIV = attribute("IV", in: line)
        }
        rewritten.append("#EXT-X-KEY:METHOD=NONE")
        continue
      }
      var result = line
      if let ref = attribute("URI", in: line) {
        let source = try local(ref, relativeTo: playlist, root: root)
        var destination = source
        if source.pathExtension == "m3u8" {
          destination = try prepare(source, root: root, workspace: workspace, depth: depth + 1)
        } else if line.hasPrefix("#EXT-X-MAP:"), let key = key {
          guard explicitIV != nil else { throw failure("加密初始化片段缺少 IV") }
          destination = try decrypt(source, key: key, iv: iv(explicitIV, sequence: sequence), workspace: workspace)
        }
        result = line.replacingOccurrences(of: "URI=\"\(ref)\"", with: "URI=\"\(destination.absoluteString)\"")
      } else if !line.isEmpty && !line.hasPrefix("#") {
        let source = try local(line, relativeTo: playlist, root: root)
        let destination: URL
        if source.pathExtension == "m3u8" {
          destination = try prepare(source, root: root, workspace: workspace, depth: depth + 1)
        } else if let key = key {
          destination = try decrypt(source, key: key, iv: iv(explicitIV, sequence: sequence), workspace: workspace)
        } else { destination = source }
        result = destination.absoluteString
        guard sequence < UInt64.max else { throw failure("分片序号溢出") }
        sequence += 1
      }
      rewritten.append(result)
    }
    let destination = workspace.appendingPathComponent(UUID().uuidString + ".m3u8")
    try rewritten.joined(separator: "\n").write(to: destination, atomically: true, encoding: .utf8)
    return destination
  }

  private func decrypt(_ source: URL, key: Data, iv: Data, workspace: URL) throws -> URL {
    var cryptor: CCCryptorRef?
    let status = key.withUnsafeBytes { k in iv.withUnsafeBytes { v in
      CCCryptorCreate(CCOperation(kCCDecrypt), CCAlgorithm(kCCAlgorithmAES), CCOptions(kCCOptionPKCS7Padding),
                      k.baseAddress, key.count, v.baseAddress, &cryptor)
    }}
    guard status == kCCSuccess, let cryptor = cryptor else { throw failure("无法初始化 AES 解密") }
    defer { CCCryptorRelease(cryptor) }
    let destination = workspace.appendingPathComponent(UUID().uuidString + "." + source.pathExtension)
    FileManager.default.createFile(atPath: destination.path, contents: nil)
    let input = try FileHandle(forReadingFrom: source), output = try FileHandle(forWritingTo: destination)
    defer { try? input.close(); try? output.close() }
    while let block = try input.read(upToCount: 1024 * 1024), !block.isEmpty {
      try check()
      var bytes = [UInt8](repeating: 0, count: block.count + kCCBlockSizeAES128), moved = 0
      let capacity = bytes.count
      let status = block.withUnsafeBytes { b in
        CCCryptorUpdate(cryptor, b.baseAddress, block.count, &bytes, capacity, &moved)
      }
      guard status == kCCSuccess else { throw failure("视频分片解密失败") }
      try output.write(contentsOf: Data(bytes.prefix(moved)))
    }
    var tail = [UInt8](repeating: 0, count: kCCBlockSizeAES128), moved = 0
    let capacity = tail.count
    guard CCCryptorFinal(cryptor, &tail, capacity, &moved) == kCCSuccess else {
      throw failure("视频密钥或分片不完整")
    }
    try output.write(contentsOf: Data(tail.prefix(moved)))
    try output.synchronize()
    return destination
  }

  private func copyPackets(input: URL, output: URL) throws {
    var source: UnsafeMutablePointer<AVFormatContext>?
    var destination: UnsafeMutablePointer<AVFormatContext>?
    var options: OpaquePointer?
    av_dict_set(&options, "protocol_whitelist", "file,data", 0)
    av_dict_set(&options, "allowed_extensions", "ALL", 0)
    av_dict_set(&options, "extension_picky", "0", 0)
    defer { av_dict_free(&options); avformat_close_input(&source) }
    var code = avformat_open_input(&source, input.path, av_find_input_format("hls"), &options)
    guard code >= 0, let context = source else { throw failure("无法打开离线分片", code) }
    code = avformat_find_stream_info(context, nil)
    guard code >= 0 else { throw failure("无法读取视频轨道", code) }
    code = avformat_alloc_output_context2(&destination, nil, "mp4", output.path)
    guard code >= 0, let target = destination else { throw failure("无法创建 MP4", code) }
    defer { avio_closep(&target.pointee.pb); avformat_free_context(target) }
    var mapping = [Int32: Int32](), counts = [Int32: Int]()
    for index in 0..<Int(context.pointee.nb_streams) {
      guard let stream = context.pointee.streams[index], let parameters = stream.pointee.codecpar else { continue }
      let type = parameters.pointee.codec_type
      guard type == AVMEDIA_TYPE_VIDEO || type == AVMEDIA_TYPE_AUDIO else { continue }
      guard let added = avformat_new_stream(target, nil) else { throw failure("无法创建输出轨道") }
      code = avcodec_parameters_copy(added.pointee.codecpar, parameters)
      guard code >= 0 else { throw failure("无法保留轨道信息", code) }
      added.pointee.codecpar.pointee.codec_tag = 0
      added.pointee.time_base = stream.pointee.time_base
      added.pointee.disposition = stream.pointee.disposition
      av_dict_copy(&added.pointee.metadata, stream.pointee.metadata, 0)
      mapping[Int32(index)] = added.pointee.index
      counts[Int32(index)] = 0
    }
    guard !mapping.isEmpty else { throw failure("视频没有可合并轨道") }
    av_dict_copy(&target.pointee.metadata, context.pointee.metadata, 0)
    code = avio_open(&target.pointee.pb, output.path, AVIO_FLAG_WRITE)
    guard code >= 0 else { throw failure("无法写入 MP4，请检查剩余空间", code) }
    var muxOptions: OpaquePointer?
    av_dict_set(&muxOptions, "movflags", "+faststart", 0)
    av_dict_set(&muxOptions, "avoid_negative_ts", "make_zero", 0)
    defer { av_dict_free(&muxOptions) }
    code = avformat_write_header(target, &muxOptions)
    guard code >= 0 else { throw failure("该编码无法无损封装为 MP4，分片已保留", code) }
    var packet = av_packet_alloc()
    guard let pkt = packet else { throw failure("合并内存不足") }
    defer { av_packet_free(&packet) }
    while true {
      try check()
      code = av_read_frame(context, pkt)
      if code == -541478725 { break } // AVERROR_EOF
      guard code >= 0 else { throw failure("读取分片失败，原文件已保留", code) }
      let inputIndex = pkt.pointee.stream_index
      if let outputIndex = mapping[inputIndex],
         let from = context.pointee.streams[Int(inputIndex)],
         let to = target.pointee.streams[Int(outputIndex)] {
        av_packet_rescale_ts(pkt, from.pointee.time_base, to.pointee.time_base)
        pkt.pointee.stream_index = outputIndex
        pkt.pointee.pos = -1
        code = av_interleaved_write_frame(target, pkt)
        av_packet_unref(pkt)
        guard code >= 0 else { throw failure("MP4 写入失败，原文件已保留", code) }
        counts[inputIndex, default: 0] += 1
      } else { av_packet_unref(pkt) }
    }
    guard counts.values.allSatisfy({ $0 > 0 }) else { throw failure("部分音视频轨道缺失，原文件已保留") }
    try check()
    code = av_write_trailer(target)
    guard code >= 0 else { throw failure("MP4 收尾失败，请检查剩余空间", code) }
    avio_flush(target.pointee.pb)
    guard let io = target.pointee.pb, io.pointee.error >= 0 else { throw failure("MP4 未完整写入") }
  }

  private func validate(_ output: URL) throws {
    var context: UnsafeMutablePointer<AVFormatContext>?
    defer { avformat_close_input(&context) }
    guard avformat_open_input(&context, output.path, av_find_input_format("mov"), nil) >= 0,
          let context = context, avformat_find_stream_info(context, nil) >= 0,
          context.pointee.nb_streams > 0, context.pointee.duration > 0 else {
      throw failure("合并文件校验失败，原始分片已保留")
    }
  }
}

#if canImport(Flutter)
import Flutter

@MainActor
final class OfflineVideoMergeController {
  private var jobs: [String: OfflineVideoRemuxer] = [:]
  func register(with messenger: FlutterBinaryMessenger) {
    FlutterMethodChannel(name: "lumebox/video_remux", binaryMessenger: messenger)
      .setMethodCallHandler { [self] call, result in
        let args = call.arguments as? [String: Any] ?? [:]
        guard let id = args["id"] as? String else {
          result(FlutterError(code: "merge", message: "无效下载任务", details: nil)); return
        }
        if call.method == "cancel" { jobs[id]?.cancel(); result(nil); return }
        guard call.method == "merge" else { result(FlutterMethodNotImplemented); return }
        guard jobs[id] == nil, let path = args["directory"] as? String else {
          result(FlutterError(code: "merge", message: "任务正在合并", details: nil)); return
        }
        let root = URL(fileURLWithPath: path).resolvingSymlinksInPath().standardizedFileURL
        let home = URL(fileURLWithPath: NSHomeDirectory()).resolvingSymlinksInPath().standardizedFileURL
        guard root.path.hasPrefix(home.path + "/"), root.lastPathComponent == id,
              id.count == 64, id.allSatisfy({ $0.isHexDigit }),
              root.deletingLastPathComponent().lastPathComponent == "video_downloads" else {
          result(FlutterError(code: "merge", message: "下载目录无效", details: nil)); return
        }
        let worker = OfflineVideoRemuxer()
        jobs[id] = worker
        Task { @MainActor in
          do {
            try await Task.detached(priority: .utility) { try worker.merge(directory: root) }.value
            jobs.removeValue(forKey: id); result(nil)
          } catch {
            jobs.removeValue(forKey: id)
            result(FlutterError(code: "merge", message: error is CancellationError ? "合并已暂停" : error.localizedDescription, details: nil))
          }
        }
      }
  }
}
#endif
