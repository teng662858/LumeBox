import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outfile = path.join(root, 'assets/js/music_vendor.js');
const result = await build({entryPoints:[path.join(here,'entry.js')], outfile,
  bundle:true,platform:'browser',format:'iife',target:'es2020',minify:true,metafile:true,legalComments:'none',
  alias:{boolbase:path.join(here,'boolean-functions.cjs')},
  banner:{js:'/* Generated by tools/music_vendor/build.mjs. Licenses: music_vendor.LICENSES.txt */'}});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules')) continue;
  let directory = path.dirname(path.resolve(input));
  while (directory !== path.dirname(directory)) {
    try {
      const pkg=JSON.parse(await fs.readFile(path.join(directory,'package.json'),'utf8'));
      if (pkg.name && pkg.version) {
        const licenses=[];
        for (const file of (await fs.readdir(directory)).filter(file=>/^(licen[sc]e|copying)(\.|$)/i.test(file)).sort()) {
          licenses.push(await fs.readFile(path.join(directory,file),'utf8'));
        }
        if (!licenses.length) throw new Error(`Missing license: ${pkg.name}`);
        packages.set(pkg.name,`${pkg.name}@${pkg.version}\n${licenses.join('\n')}`);
        break;
      }
    } catch (error) { if(error.code!=='ENOENT')throw error; }
    directory=path.dirname(directory);
  }
}
await fs.writeFile(path.join(root,'assets/js/music_vendor.LICENSES.txt'),
  [...packages.entries()].sort(([a],[b])=>a.localeCompare(b)).map(([,text])=>text.replace(/\r\n/g,'\n').split('\n').map(line=>line.replace(/\t/g,'  ').trimEnd()).join('\n')).join('\n\n--------------------\n\n'));
