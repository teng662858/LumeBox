    Readable: Readable,
    Writable: Writable,
    Duplex: Duplex,
    Transform: Transform,
    PassThrough: PassThrough,
    pipeline: pipeline,
    finished: finished,
    promises: { pipeline: pipeline, finished: finished }
  };
  streamModule.default = streamModule;

  registry.stream = streamModule;
  registry['stream/promises'] = streamModule.promises;
  registry['stream/web'] = {};
})();
''';
}

