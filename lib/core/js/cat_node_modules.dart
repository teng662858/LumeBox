/// 猫源沙箱的 **Node 模块垫片**（只对猫源注入，见 `LumeSourcePolyfills.forSection`）。
///
/// 真实猫源脚本基本都是 Node 目标的打包产物（`require("node:crypto")`、
/// `require("node:http")`、`require("node:path")`…），引擎里没有这些内建，
/// 脚本在**加载阶段**就会因为 require 抛错而整包失败。本文件把这些模块补齐：
///
/// - `crypto`：md5 / sha1 / sha256 哈希、HMAC、randomBytes / randomUUID（纯 JS）；
/// - `events` / `stream` / `timers/promises` / `assert` / `path` / `util` / `os`：
///   纯 JS 的常用子集，够脚本初始化与数据处理用；
/// - `http` / `https`：**不做真实 socket**，`request` / `get` 全部经 `fetch`
///   桥接到宿主网络层（宪法：网络请求只能走宿主桥），响应按 Node 的
///   `IncomingMessage` 形状投递（statusCode / headers / 'data' / 'end' / pipe）；
/// - `fs`：**内存虚拟文件系统**，不落盘、不跨上下文、无宿主权限（脚本在
///   加载期 require("fs") 与做临时缓存时可用；真正的持久化仍必须走宿主桥）。
///
/// 能力边界没有任何扩大：这里没有 socket、没有真实文件、没有进程能力，
/// 只有「让 Node 味道的纯 JS 脚本能跑起来」的模拟层。
